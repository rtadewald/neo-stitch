"""Pede a um modelo multimodal (Gemini via OpenRouter) O QUE se mexe e COMO. Centavos por chamada.

    uv run descrever_video.py <video.mp4> <saida.md> [--regioes analise/regioes.json] [--lento 4]
    uv run descrever_video.py <video-ref.mp4> <saida.md> --comparar <html.mp4>

O vídeo vai desacelerado (--lento, padrão 4x) para o modelo enxergar eventos curtos; os tempos pedidos voltam na
escala ORIGINAL. Com --regioes, os ids do ler_video.py entram no prompt e ele descreve cada região pelo id.
Com --comparar, manda os dois vídeos e pede as diferenças de ritmo, intensidade e caráter (segunda opinião).

O tempo fino vem do ler_video.py (exato); o modelo erra eventos curtos. Use isto para o QUE e o COMO.
"""
from __future__ import annotations

import argparse
import base64
import json
import subprocess
import tempfile
import urllib.request
from pathlib import Path

import _comum as C

PROMPT_LER = """You are analysing a reference video generated by an image-to-video model from a still UI screenshot.
It is slowed down {lento}x: report every time in the ORIGINAL timeline (divide what you see by {lento}).
Goal: someone will rebuild this UI as a living HTML page, so describe the MOTION precisely.

Answer in Brazilian Portuguese, as Markdown, with these sections:
1. **Ritmo geral**: one paragraph (calm/busy, loop or not, what leads the eye).
2. **Elementos**: a table | elemento | o que faz | quando (s) | como (easing, velocidade, intensidade) | região |.
   Name concrete UI elements (núcleo, linha até "Comercial", barra de CPU...). {regioes}
3. **Sequência**: a timeline in text, one line per event, in original seconds.
4. **Artefatos**: anything that is a generation error and must NOT be copied: text or numbers that change or melt,
   labels that swap, objects that appear or vanish, camera moves, layout shifts. Be strict.
5. **Intensidade**: for each element, small/medium/large amplitude and whether it glows.
"""

PROMPT_COMPARAR = """VIDEO 1 is the REFERENCE (from an image-to-video model). VIDEO 2 is an HTML RECREATION of the same UI.
Both are slowed down {lento}x; report times in the original timeline. Ignore text/label changes in VIDEO 1 (artefacts).
Answer in Brazilian Portuguese, as Markdown:
1. **O que falta na recriação**: motion present in VIDEO 1 that is missing or much weaker in VIDEO 2 (where, when).
2. **O que sobra**: motion in VIDEO 2 that VIDEO 1 does not have.
3. **Caráter**: differences in rhythm, easing, speed, amplitude, glow, texture of motion (e.g. "smoke vs rigid rotation").
4. **Prioridades**: the 5 changes that would bring VIDEO 2 closest to VIDEO 1, most important first.
Be concrete and critical; do not praise.
"""


def lento_b64(video: Path, fator: float) -> str:
    with tempfile.TemporaryDirectory() as tmp:
        saida = Path(tmp) / 'lento.mp4'
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(video), '-vf',
                        f'setpts={fator}*PTS,scale=960:-2,fps=24', '-an', '-c:v', 'libx264', '-crf', '26',
                        '-pix_fmt', 'yuv420p', str(saida)], check=True)
        return base64.b64encode(saida.read_bytes()).decode()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('video', type=Path)
    ap.add_argument('saida', type=Path)
    ap.add_argument('--regioes', type=Path)
    ap.add_argument('--comparar', type=Path, help='o vídeo da página (html.mp4)')
    ap.add_argument('--lento', type=float, default=4)
    ap.add_argument('--modelo', default='google/gemini-3.8-flash')
    a = ap.parse_args()
    C.exigir('ffmpeg')

    if a.comparar:
        texto = PROMPT_COMPARAR.format(lento=a.lento)
        videos = [a.video, a.comparar]
    else:
        reg = ''
        if a.regioes:
            meta = C.ler_json(a.regioes)
            linhas = [f'{r["id"]}: box x={r["caixa"][0]} y={r["caixa"][1]} w={r["caixa"][2]} h={r["caixa"][3]} '
                      f'(on a {meta["largura_ref"]}px wide frame), peaks at {r["picos_s"]} s' for r in meta['regioes'][:16]]
            reg = 'A pixel motion map found these regions; refer to them by id:\n' + '\n'.join(linhas)
        texto = PROMPT_LER.format(lento=a.lento, regioes=reg)
        videos = [a.video]

    partes = [{'type': 'text', 'text': texto}]
    for v in videos:
        partes.append({'type': 'video_url', 'video_url': {'url': f'data:video/mp4;base64,{lento_b64(v, a.lento)}'}})
    corpo = json.dumps({'model': a.modelo, 'messages': [{'role': 'user', 'content': partes}]}).encode()
    req = urllib.request.Request('https://openrouter.ai/api/v1/chat/completions', data=corpo, headers={
        'Authorization': f'Bearer {C.chave_openrouter()}', 'Content-Type': 'application/json', 'X-Title': 'neo-stitch video2html'})
    with urllib.request.urlopen(req, timeout=300) as r:
        resp = json.loads(r.read())
    if 'choices' not in resp:
        raise SystemExit(f'ERRO da API: {json.dumps(resp)[:600]}')
    conteudo = resp['choices'][0]['message']['content']
    custo = (resp.get('usage') or {}).get('cost')
    cab = f'<!-- {a.modelo} · {"comparação" if a.comparar else "leitura"} · lento {a.lento}x · custo ${custo} -->\n\n'
    a.saida.parent.mkdir(parents=True, exist_ok=True)
    a.saida.write_text(cab + conteudo + '\n', encoding='utf-8')
    print(f'{a.saida} · custo ${custo}')


if __name__ == '__main__':
    main()
